const NATIVE_WET_ACTOR = "H-v1-p0p0-m0i8t-2-0o03jwb";

/**
 * Producer contract fixtures, not native gameplay/autonomy certification.
 * Identities, terrain and initial positions are generated by their real owners;
 * urgent need, clear weather, an optional initial clock/heading, and the explicit
 * v5 capability are controlled inputs. Actual adoption/routine selection makes
 * every body/task, and the real collector must decide whether sight is lawful.
 */
function fixture(options: { readonly night?: boolean; readonly away?: boolean; readonly dryTarget?: boolean } = {}) {
  const state = createWorld(options.dryTarget ? "resident activity executable rest approach" : "marsh wait 41", "wild");
  if (options.night) {
    const clockShift = WORLD_NIGHT_START_TICK - state.meta.completedTick;
    state.meta.completedTick = WORLD_NIGHT_START_TICK;
    state.tide = tideAtTick(state.meta.completedTick);
    // A controlled initial clock must keep every existing recipe's pending
    // schedule equally far in the future; this does not execute production.
    for (const settlement of state.settlements) {
      for (const recipe of settlement.recipes) recipe.nextRunTick += clockShift;
    }
    for (const resident of state.residents) {
      resident.perception = createActorPerceptionState(resident.identity.stableId, state.meta.completedTick);
    }
  }
  const tick = state.meta.completedTick;
  state.weather = { kind: "clear", intensity: 0, windX: 0, windY: 0, nextChangeTick: tick + 1_000 };
  for (const resident of state.residents) {
    resident.needs = { food: 100_000, rest: 100_000, belonging: 100_000 };
    resident.condition.exhaustion = 100_000;
  }
  for (const contract of state.contracts) {
    contract.playerExclusiveUntilTick = tick + 1_000;
    contract.dueTick = tick + 2_000;
  }
  const selected = options.dryTarget ? state.residents.find((resident) => {
    const source = resolveResidentWorldPlacement(state, resident)?.position;
    const target = residentSettlementRestTarget(state, resident);
    if (!source || !target || !residentRestTargetHasDrySupport(state, source)
      || !residentRestTargetHasDrySupport(state, target)) return false;
    const delta = worldPositionDelta(source, target);
    return Math.abs(delta.x) + Math.abs(delta.y) === 1_000;
  }) : state.residents.find(({ identity }) => identity.stableId === NATIVE_WET_ACTOR);
  if (!selected) throw new Error("Native source does not supply the selected rest contract");
  const actorId = selected.identity.stableId;
  const target = residentSettlementRestTarget(state, selected);
  if (!target) throw new Error("Native selected resident has no settlement rest target");
  selected.needs.rest = 900_000;
  selected.condition.exhaustion = 300_000;
  expect(adoptResidentActivities(state)).toBe(true);
  // Explicit protocol input, not an injected task, decision or body placement.
  state.residents = state.residents.map((resident) => replaceResidentActivity(resident, {
    ...resident.activity!, version: RESIDENT_ENVIRONMENT_ACTIVITY_VERSION,
    ownerId: RESIDENT_ENVIRONMENT_ACTIVITY_OWNER_ID, inspectionTask: null,
  }));
  expect(prepareResidentRestActivities(state)).toBe(true);
  const get = () => state.residents.find(({ identity }) => identity.stableId === actorId)!;
  expect(get().activity?.restTask).toMatchObject({ origin: "selected", phase: "approaching", target });
  if (options.away) {
    const resident = get();
    state.residents[state.residents.indexOf(resident)] = replaceResidentActivity(resident, {
      ...resident.activity!, poses: [{ ...resident.activity!.poses[0]!, heading: headingFromRadians(Math.PI) }],
    });
  }
  assertWorldInvariants(state);
  return { state, actorId, target, get };
}

type Fixture = ReturnType<typeof fixture>;

function publish(current: Fixture, origin = {
  x: Math.floor(current.target.localX / 1_000) - 60,
  y: Math.floor(current.target.localY / 1_000) - 60,
}) {
  const economy = createWorldView(current.state);
  const window = createRegionalTerrainWindow(current.state.meta.rootSeed,
    createTerrainRegionStreamingState({ rootSeed: current.state.meta.rootSeed }), origin);
  const world = createRegionalWorldView(economy, window,
    projectRegionalCartographyWindow(createRegionalCartography(current.state.meta.rootSeed), window));
  return { ...current, economy, window, world };
}

type Published = ReturnType<typeof publish>;

function impact(current: Fixture, index = 0) {
  const sample = createPhysicalSoundSample({
    id: `rest-contract-impact-${index}`, sourceId: `OBJECT-CONTRACT-${index}`,
    acousticEventId: `acoustic:rest-contract-${index}`, position: current.target,
    soundClass: "physical-thud", soundLoudness: FIXED_POINT, soundRangeUnits: 8_000, soundInterrupt: "none",
  });
  if (!sample) throw new Error("Controlled hearing stimulus must be canonical");
  return sample;
}

function inputFor(current: Published): HumanPerceptionInput {
  const sample = impact(current);
  return { world: current.world, window: current.window, targetTick: current.state.meta.completedTick + 1,
    playerSamples: [], physicalSoundSamples: [sample], soundSamplePhases: [{ sampleId: sample.id, phase: 0 }] };
}

function collect(current: Published) {
  const input = inputFor(current);
  const before = JSON.stringify(input);
  const batches = collectExistingHumanObservations(input);
  expect(humanObservationCollectionRejected(batches)).toBe(false);
  expect(JSON.stringify(input)).toBe(before);
  return batches;
}

function observations(current: Published) {
  return collect(current).find(({ observerId }) => observerId === current.actorId)?.observations ?? [];
}

function expectHearingWithoutGround(current: Published) {
  const seen = observations(current);
  expect(seen.some(({ id }) => id === residentRestSurfaceObservationId(current.actorId, current.target))).toBe(false);
  expect(seen).toContainEqual(expect.objectContaining({ channel: "hearing", perceivedClass: "physical-thud",
    identification: "anonymous", subjectId: null }));
}

describe("pending selected-rest surface observation producer", () => {
  it("produces one real qualitative information fact without identity, pressure or source mutation", () => {
    const current = publish(fixture());
    const before = JSON.stringify(current.state);
    const seen = observations(current);
    const information = seen.filter(({ interrupt }) => interrupt === "information");
    expect(information).toHaveLength(1);
    expect(information[0]).toMatchObject({ id: residentRestSurfaceObservationId(current.actorId, current.target),
      observerId: current.actorId, observedAtTick: current.state.meta.completedTick + 1,
      channel: "vision", perceivedClass: "water-covered-ground", identification: "classified",
      subjectId: null, area: { center: current.target, radiusUnits: 0 }, interrupt: "information" });
    expect(information[0]!.confidence).toBeGreaterThan(0);
    expect(information[0]!.salience).toBeLessThanOrEqual(300_000);
    const cognition = stepActorPerception(current.get().perception,
      { tick: current.state.meta.completedTick + 1, observations: information });
    expect(cognition).toMatchObject({ suspicion: "unaware", suspicionPressure: 0, search: null, salientMemory: [] });
    expect(JSON.stringify(current.state)).toBe(before);
  });

  it("does not learn a peripheral target behind the controlled phase-zero heading", () => {
    expectHearingWithoutGround(publish(fixture({ away: true })));
  });

  it("does not learn an unlit nighttime target without a completed beacon", () => {
    const current = publish(fixture({ night: true }));
    expect(current.state.settlements.every(({ project }) => project.status !== "complete")).toBe(true);
    const targetIndex = (Math.floor(current.target.localY / 1_000) - current.window.origin.y) * current.world.terrain.width
      + Math.floor(current.target.localX / 1_000) - current.window.origin.x;
    expect(buildOutdoorIlluminationField(current.world)?.physicalIllumination[targetIndex]).toBeLessThan(200_000);
    expectHearingWithoutGround(current);
  });

  it("treats an out-of-frame target as ordinary absence without rejecting its in-frame listener", () => {
    const current = fixture();
    const frame = publish(current, { x: Math.floor(current.target.localX / 1_000) - 120,
      y: Math.floor(current.target.localY / 1_000) - 60 });
    const batches = collect(frame);
    expect(batches.some(({ observerId }) => observerId === current.actorId)).toBe(true);
    expect(batches.find(({ observerId }) => observerId === current.actorId)?.observations).toEqual([]);
  });

  it("returns a legitimate empty frame when both body and target are outside", () => {
    const current = fixture();
    const frame = publish(current, { x: 1_000, y: 1_000 });
    const batches = collect(frame);
    expect(batches).toEqual([]);
    expect(humanObservationCollectionRejected(batches)).toBe(false);
  });

  it("rejects a foreign task target before any partial supplemental observer receipt", () => {
    const current = publish(fixture());
    const resident = current.world.residents.find(({ identity }) => identity.stableId === current.actorId)!;
    resident.activity = { ...resident.activity!, restTask: { ...resident.activity!.restTask!,
      target: createWorldPosition(current.target.region, current.target.localX + 1_000, current.target.localY) } };
    const receipt = vi.fn<(receipts: readonly HumanSupplementalListeningReceipt[]) => void>();
    const input = inputFor(current);
    const batches = collectExistingHumanObservations(input, receipt);
    expect(batches).toEqual([]);
    expect(humanObservationCollectionRejected(batches)).toBe(true);
    expect(receipt).not.toHaveBeenCalled();
  });

  it("filters real visual information only after valid physical arrival and authenticated sleeping admission", () => {
    const current = fixture({ dryTarget: true });
    const seen = observations(publish(current));
    expect(seen).toContainEqual(expect.objectContaining({ interrupt: "information", channel: "vision" }));
    for (let phase = 1; phase <= 10; phase += 1) expect(advanceResidentRestActivities(current.state, phase)).not.toBeNull();
    const arrived = current.get();
    expect(arrived.activity?.restTask?.phase).toBe("arrived");
    expect(residentAtSettlementRestDestination(arrived)).toBe(true);
    // Controlled, valid sleep receipt exercises the existing channel gate;
    // it is not an injected sleep-plus-pending-task or autonomy demonstration.
    const asleep = replaceResidentCircadian(arrived, { atTick: current.state.meta.completedTick,
      circadian: { ...arrived.circadian!, posture: { state: "asleep", enteredAtTick: current.state.meta.completedTick } } });
    const accepted = gateResidentCircadianObservations({ resident: asleep,
      targetTick: current.state.meta.completedTick + 1, observations: seen });
    expect(accepted).not.toBeNull();
    expect(accepted?.some(({ channel }) => channel === "vision")).toBe(false);
    expect(accepted).toEqual(seen.filter(({ channel }) => channel === "hearing"));
    expect(accepted).toHaveLength(1);
  });

  it("preserves every reachable hearing slot alongside information within the unchanged total bound", () => {
    const current = fixture();
    // Real wet-target waiting retains all ten accepted phase poses. The v5
    // interval cannot honestly supply sixteen unique player phase ordinals.
    for (let phase = 1; phase <= 10; phase += 1) expect(advanceResidentRestActivities(current.state, phase)).not.toBeNull();
    const frame = publish(current);
    const source = resolveResidentWorldPlacement(current.state, current.get())!.position;
    const playerPosition = createWorldPosition(source.region, source.localX - 1_000, source.localY);
    const playerSamples = Array.from({ length: 10 }, (_, index) => {
      const sample = createPlayerSenseSample({ id: `rest-contract-player-${index}`, sampleOrdinal: index,
        position: playerPosition, movementSalience: 0, lightVisibility: FIXED_POINT,
        soundLoudness: FIXED_POINT, soundRangeUnits: 8_000, soundClass: "movement-sound", soundInterrupt: "none" });
      if (!sample) throw new Error("Controlled player stimulus must be canonical");
      return sample;
    });
    const voices = Array.from({ length: 8 }, (_, index) => {
      const sample = createSupplementalSoundSample({ id: `rest-contract-voice-${index}`,
        sourceActorId: `HUMAN-CONTRACT-${index}`, expressionEventId: `expression:rest-contract-${index}`,
        position: current.target, soundClass: "human-vocalization", soundLoudness: FIXED_POINT,
        soundRangeUnits: 8_000, soundInterrupt: "none" });
      if (!sample) throw new Error("Controlled vocal stimulus must be canonical");
      return sample;
    });
    const impacts = Array.from({ length: 8 }, (_, index) => impact(current, index));
    const batches = collectExistingHumanObservations({ world: frame.world, window: frame.window,
      targetTick: current.state.meta.completedTick + 1, playerSamples, supplementalSoundSamples: voices,
      physicalSoundSamples: impacts, soundSamplePhases: [...voices, ...impacts].map(({ id }) => ({ sampleId: id, phase: 0 })) });
    expect(humanObservationCollectionRejected(batches)).toBe(false);
    const seen = batches.find(({ observerId }) => observerId === current.actorId)?.observations;
    expect(seen?.filter(({ channel }) => channel === "hearing")).toHaveLength(26);
    expect(seen?.filter(({ interrupt }) => interrupt === "information")).toHaveLength(1);
    expect(seen).toHaveLength(37);
    expect(HUMAN_PERCEPTION_MAX_OBSERVATIONS_PER_RESIDENT).toBe(48);
    expect(seen!.length).toBeLessThanOrEqual(HUMAN_PERCEPTION_MAX_OBSERVATIONS_PER_RESIDENT);
  });
});
